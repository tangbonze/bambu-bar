function t(locale, key, params) {
  const loc = UI[locale] ? locale : 'zh-CN';
  let s = UI[loc][key];
  if (s == null) {
    const l = STRINGS[loc] || STRINGS['zh-CN'];
    s = l[key];
  }
  if (s == null) s = key;
  if (params && typeof s === 'string') {
    for (const [k, v] of Object.entries(params)) {
      s = s.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
    }
  }
  return s;
}

// 面板/设置窗需要的整份字符串包（按当前语言），跨 IPC 一次性下发。
function bundle(locale) {
  const loc = UI[locale] ? locale : 'zh-CN';
  return { locale: loc, table: { ...(STRINGS[loc] || {}), ...UI[loc] } };
}

module.exports = { t, bundle, UI };
